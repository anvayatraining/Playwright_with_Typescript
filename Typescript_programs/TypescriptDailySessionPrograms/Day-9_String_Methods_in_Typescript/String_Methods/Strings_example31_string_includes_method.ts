// Task: Check whether the string "Beginner TypeScript Guide" contains the word "Guide".

// includes() checks whether the given text is present in the string. It returns true or false.
// The check is case sensitive.
// Syntax: string.includes(searchText)

let str24 = "Beginner TypeScript Guide";
console.log(str24.includes("Guide"));

// Output:
// true

