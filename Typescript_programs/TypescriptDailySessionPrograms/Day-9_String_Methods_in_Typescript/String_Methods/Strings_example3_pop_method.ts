// Task: Remove the last element from the array [10, 20, 30].

// pop() removes the LAST element of an array.
// Syntax: array.pop()

let arr2 = [10, 20, 30];
arr2.pop();            // removes 30
console.log(arr2);

// Output:
// [ 10, 20 ]

