// Task: Add the number 4 to the end of the array [1, 2, 3].

// push() adds one or more elements to the END of an array.
// Syntax: array.push(element1, ..., elementN)

let arr1 = [1, 2, 3];
arr1.push(4);          // adds 4 at the end
console.log(arr1);

// Output:
// [ 1, 2, 3, 4 ]

