// Task: Reverse the order of the elements of the array [1, 2, 3].

// reverse() reverses the order of the elements. It CHANGES the original array.
// Syntax: array.reverse()

let arr18 = [1, 2, 3];
arr18.reverse();
console.log(arr18);

// Output:
// [ 3, 2, 1 ]

